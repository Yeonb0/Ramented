-- 라멘타쿠 v2 스키마 (Phase 1 : 가게 · 정기 영업시간)
-- 메뉴 (shop_ramen) · 라멘 종류 (ramen) 는 다음 마이그레이션에서 추가한다
-- H2 (테스트, PostgreSQL 모드) 와 PostgreSQL 양쪽에서 돌아가는 문법만 쓴다

CREATE TABLE ramen_shop (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name             VARCHAR(100)     NOT NULL,  -- 지점명을 뺀 이름
  branch_name      VARCHAR(50),                -- 홍대점 · 합정본점 등. 없으면 NULL
  latitude         DOUBLE PRECISION NOT NULL,  -- WGS84 (공공데이터 EPSG:5174 변환)
  longitude        DOUBLE PRECISION NOT NULL,
  address          VARCHAR(255)     NOT NULL,  -- 공공데이터 도로명 주소
  hours_raw        VARCHAR(500),               -- seed-survey 원문 (주문마감 · 재료 소진 등 보존)
  instagram_handle VARCHAR(100),
  kakao_place_id   VARCHAR(30) UNIQUE          -- 링크용으로만 저장
);

-- 요일별 정기 영업시간. 정기 휴무 요일은 행이 없다
CREATE TABLE shop_hours (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shop_id     BIGINT   NOT NULL REFERENCES ramen_shop (id),
  day_of_week INTEGER  NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),  -- 1 = 월 … 7 = 일
  open_time   TIME     NOT NULL,
  close_time  TIME     NOT NULL,
  break_start TIME,
  break_end   TIME,
  CONSTRAINT uq_shop_hours_day UNIQUE (shop_id, day_of_week)
);
